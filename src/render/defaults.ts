import { getLanguage } from "obsidian";

import { noteWords } from "./words";

/**
 * Шаблон секции по умолчанию.
 *
 * **Вёрстка выведена из хранилища владельца, а не из вкуса.** В
 * `Base/Библиотека/` уже лежат 924 коллаута `> [!quote]` и 160 `[!Cite]`, а
 * голых блочных цитат почти нет — значит цитата это коллаут `> [!quote]+`, и
 * знак `+` (развёрнутый по умолчанию) стоит потому, что свёрнутая цитата в
 * конспекте бесполезна. Подпись ссылки датой и место ссылки сразу под цитатой —
 * его собственная привычка, снятая с готовых заметок:
 * `[25.10.2022 10:46](calibre://view-book/…?open_at=epubcfi(…))`. Сама дата при
 * этом пишется как `20221025 1046`, а не точками: у владельца сквозной формат
 * `YYYYMMDD HHMM`, и держать в одной заметке две даты от одного плагина —
 * `beresta-last-sync: 20260818 1047` сверху и `19.08.2023 12:30` в блоке —
 * значит выдумать формат, которого у него нет (прогон глазами 20260818, п. 11).
 *
 * **Заголовок коллаута — путь по оглавлению**, ради которого делалась миграция
 * v32: у 171 выписки из 287 путь глубже одного уровня, и однострочная подпись
 * («глава такая-то») была бы подписью НЕ ТОГО места у трёх четвертей выписок.
 *
 * **Якорь `^hl-…` — отдельной строкой после пустой строки, следом за
 * коллаутом.** Это прямой вывод замера задачи 2, и он проверен тремя
 * независимыми способами: разметочный кэш ставит идентификатор на секцию
 * `type: "callout"`, встраивание `![[Файл#^hl-…]]` рисует коллаут целиком,
 * переход по ссылке подсвечивает его же. Две другие раскладки (впритык и
 * внутри коллаута) работают тоже, но оставляют висящий `<br>` внутри абзаца.
 *
 * **Вид коллаута — не украшение, а утверждение.** `[!quote]` в конспекте
 * значит «дальше слова книги», поэтому голова берётся полем `{{callout}}`, а
 * не пишется в шаблоне буквой: блок без якоря-цитаты (росчерк, пометка на
 * пустом месте) получает `[!note]` — «пометка», карандаш, а не прямая речь
 * автора. Прогон глазами 20260818 нашёл ровно обратное (находка 10): росчерк
 * стоял в заметке коллаутом `[!quote]`, и через полгода его нельзя было
 * отличить от цитаты ничем.
 *
 * **Цвет — меткой коллаута (`[!quote|blue]`), а не словом в тексте.** Решение
 * принято против прежнего «цвета в шаблоне нет вовсе» и против «написать имя
 * цвета словом», и вот доводы по порядку.
 *
 * *Почему не молчать.* Цветов у владельца четыре, и выбирал он их не случайно
 * — а в заметке от разметки не оставалось следа вовсе (находка 10). Архив
 * `.beresta/` цвет хранит, но заметка — единственная поверхность, на которую
 * человек смотрит каждый день.
 *
 * *Почему не словом.* «Синим» стояло бы на 217 блоках из 287 — строка, которая
 * почти никогда не меняется, не несёт ничего, а место в строке чтения занимает
 * на каждом блоке. Спрятать самый частый цвет и назвать остальные было бы
 * догадкой о человеке, а не правилом: у самого приложения цвет по умолчанию
 * ЖЁЛТЫЙ (`docs/schema/schema.md`, палитра `AnnotationColor`), а синими у
 * владельца оказались 217 просто потому, что он так размечал. Хуже того,
 * «самый частый» зависит от соседей: одна новая выписка меняет большинство —
 * и вся секция переписывается, хотя данные прежних блоков не менялись.
 * Наконец, цвет — свойство ЗРИТЕЛЬНОЕ; слово «жёлтым» возвращает имя цвета, а
 * не сам цвет.
 *
 * *Что даёт метка.* Ни одного знака в строке, которую человек читает; открытое
 * слово в исходнике заметки, видное и без Obsidian; обычный поиск по
 * `[!quote|yellow]` находит все жёлтые; и `styles.css` красит по этой метке
 * узкий корешок слева — красками ТЕМЫ (`--color-yellow` и соседние), а не
 * своими. Выключили плагин, открыли заметку чужим средством, поставили тему
 * без этих красок — остаётся ровно тот коллаут, что был, и слово `yellow`
 * рядом с ним.
 *
 * **Жест — словом в подписи, и только когда он не «выделение»** (`Подчёркнуто
 * · [20260806 1206](…)`). Подчёркивание и выделение — разные действия, и
 * человек различал их, когда делал; до 20260818 они рисовались неотличимо.
 * Молчать про `highlight` — не догадка: `[!quote]` со ссылкой на место уже
 * говорит «этот кусок книги вы пометили», то есть ровно то, что значит
 * `highlight`. Названо отличное от обычного — и потому заметно.
 *
 * **Чего в шаблоне нет нарочно.** Полей `intent`, `topic`, `processed` — они
 * рабочие, а не читательские. Группировки по цвету — одна куча и четыре
 * хвостика. Ничего из этого не теряется: заметка — поверхность для чтения, а
 * архивом остаётся `.beresta/`, откуда задача 16 достаёт всё до последнего
 * поля скриптом на сорок строк без Beresta и без Obsidian.
 *
 * **Как читать эти строки.** `{{имя}}` — подставить значение. `{{#имя}}…{{/имя}}`
 * — повторить по списку (`annotations`) или показать, если значение непусто
 * (`comment`, `tags`, `caption`). Метка куска, стоящая на строке одна,
 * съедает свою строку целиком; поэтому `{{#comment}}` в конце строки, а не на
 * своей — иначе при пустой мысли внутри коллаута осталась бы пустая строка, а
 * пустая строка коллаут закрывает.
 */
/// Язык интерфейса Obsidian — через его собственный `getLanguage()` (ревью
/// каталога 20260927). С 0.3.2 — ТОЛЬКО через него, и `minAppVersion` поднят до
/// 1.8.7, где он появился: каталог заворачивал 0.3.1 за вызов API новее
/// заявленной версии (`obsidianmd/no-unsupported-api`), и запасной путь через
/// `localStorage` он же ругал предупреждением. Obsidian старше 1.8.7 по
/// `versions.json` остаётся на 0.3.1.
///
/// Пустой ответ — английский: плагин лежит в каталоге сообщества с английским
/// описанием, и русская строка тому, о ком мы ничего не знаем, — та самая беда,
/// от которой заход и затевался.
export function interfaceLanguage(): string {
  try {
    const language = getLanguage();
    if (typeof language === "string" && language.length > 0) return language;
  } catch {
    // Приложение не ответило — английский.
  }
  return "en";
}

/// Шаблон по умолчанию для этого языка интерфейса.
///
/// **Зачем это вообще** (долг 0.3а, решение владельца 20260925). Шаблон писал
/// «## Выписки из Beresta» ЛЮБОМУ — а плагин лежит в каталоге сообщества с
/// полностью английским описанием, то есть его ставят и англоязычные читатели.
/// Первое, что такой человек видел в своей заметке, — русская строка.
///
/// ⚠️ **Списка известных заголовков не понадобилось, и это стоит сказать вслух:**
/// решение владельца называло его первым пунктом, но чтение кода показало, что
/// он не нужен. Секцию опознают МАРКЕРЫ (`SECTION_BEGIN`/`SECTION_END` в
/// `merge/zones.ts`), а заголовок внутри них — обычный машинный блок с
/// отпечатком в `data.json`: совпал отпечаток — заголовок наш и перепишется,
/// не совпал — он человеческий, остаётся и получает жалобу о расхождении
/// (`fuse.ts`, ветка `kind: "head"`). Значит у уже собранных заметок заголовок
/// сам переедет на язык интерфейса, а правленный рукой — уцелеет.
///
/// ⚠️ **Переводятся ДВЕ строки шаблона, а не одна.** Подпись мысли человека
/// («**Мысль.**») стояла в шаблоне тем же русским текстом, и сборка примера
/// заметки 20260925 нашла её ровно там, где заголовок уже был переведён:
/// английская голова секции и русское слово внутри — хуже, чем честно русское
/// всё. Остальные слова заметки живут в `words.ts`, там же замер долга числом.
///
/// Замена идёт функцией, а не строкой: `$&` и прочие знаки замены в словаре
/// могут появиться завтра, и тогда строковая замена подставила бы не то.
export function defaultTemplate(language: string = interfaceLanguage()): string {
  const words = noteWords(language);
  const russian = noteWords("ru");
  return DEFAULT_TEMPLATE.replace(russian.heading, () => words.heading).replace(
    russian.thought,
    () => words.thought,
  );
}

export const DEFAULT_TEMPLATE = [
  "## Выписки из Beresta",
  // Мысль о книге — простым абзацем, без своей подпорки: это слова человека, и
  // украшать их незачем. Пусто — строки нет вовсе.
  "{{#thought}}",
  "",
  "{{thought}}",
  "",
  // Якорь обязателен: без него блок мысли слиянию не принадлежит, и правка
  // человека в заметке затиралась бы каждым проходом.
  "^{{thoughtAnchor}}",
  "{{/thought}}",
  "{{#annotations}}",
  "",
  "> [!{{callout}}]+ {{heading}}",
  "> {{text}}{{#caption}}",
  "> {{caption}}{{/caption}}{{#comment}}",
  ">",
  "> **Мысль.** {{comment}}{{/comment}}{{#tags}}",
  ">",
  "> {{tags}}{{/tags}}",
  "",
  "^{{anchor}}",
  "{{/annotations}}",
  "",
].join("\n");
