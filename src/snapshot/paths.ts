/**
 * Адрес снимка внутри хранилища.
 *
 * **Эти три строки — общая граница со Swift.** Ровно те же имена объявлены в
 * `VaultLocation` на стороне приложения (`exportFolderName`, `booksFolderName`,
 * `indexFileName`), и расхождение между сторонами означает, что приложение
 * пишет в одно место, а плагин читает другое, — молча, без единой ошибки, с
 * заметками, в которых ничего не появляется. Поэтому равенство сверяется
 * тестом `test/vault-address.test.ts`, который читает объявление из исходника
 * Swift, а не повторяет строку в третий раз.
 *
 * Точка в начале имени папки — не украшение: по замеру задачи 2 Obsidian такую
 * папку не показывает в дереве, не индексирует в поиске и не тянет в граф, но
 * полностью обслуживает через `vault.adapter`. Снимок лежит внутри хранилища и
 * при этом не мешается человеку под ногами.
 *
 * **Почему отдельный файл, а не `main.ts`.** Разбор снимка обращается к этим
 * же строкам, а `main.ts` будет обращаться к разбору (задача 14). Оставь
 * объявления в точке входа — получилась бы петля импортов; сборщик её проглотит,
 * но порядок вычисления модулей станет тем, о чём придётся помнить. Точка входа
 * их перевыставляет, чтобы прежние потребители ничего не заметили.
 */
export const EXPORT_FOLDER_NAME = ".beresta";

/** Папка осколков по книгам внутри папки снимка: `.beresta/books/`. */
export const EXPORT_BOOKS_FOLDER_NAME = "books";

/** Указатель снимка: `.beresta/index.json`. Заголовок и список осколков. */
export const EXPORT_INDEX_FILE_NAME = "index.json";

/** Путь указателя от корня хранилища. */
export function indexPath(): string {
  return `${EXPORT_FOLDER_NAME}/${EXPORT_INDEX_FILE_NAME}`;
}

/**
 * Путь осколка от корня хранилища по строке `file` из указателя.
 *
 * Строка склеивается с папкой снимка, а не с корнем хранилища: указатель
 * называет осколки ОТНОСИТЕЛЬНО себя (`books/<uuid>.jsonld`), и читателю не
 * нужно знать нашу раскладку. Проверять строку на пригодность здесь нечем —
 * это делает `shardFileName`, и вызывать её обязан тот, кто собирается читать.
 */
export function shardPath(file: string): string {
  return `${EXPORT_FOLDER_NAME}/${file}`;
}

/**
 * Имя осколка внутри `books/`, если строка указателя действительно на него
 * похожа, — иначе `undefined`.
 *
 * **Зачем сторож на чтении.** `index.json` лежит в хранилище человека открытым
 * текстом: вписать в него `books/../../.obsidian/plugins/чужой/data.json` может
 * кто угодно — чужой скрипт, конфликт синхронизации, опечатка. Мы обещали в
 * README, что не читаем ничего за пределами хранилища и ничего, кроме своей
 * папки; обещание держится этой функцией, а не тем, что строку в указатель
 * пишем мы сами.
 *
 * Правило дословно повторяет `VaultSnapshotPlan.shardName(in:)` на стороне
 * Swift — и это не совпадение, а единственное разумное устройство: то, что
 * писатель не считает своим файлом и потому не удаляет, читатель не должен
 * считать своим файлом и потому не должен читать.
 *
 * **Имя НЕ приводится к NFC**, хотя Swift приводит его при записи. Причина в
 * файловой системе: APFS хранит имя ровно так, как его дали, и не считает две
 * формы Unicode одним именем. Приведи мы имя здесь — и файл, записанный в
 * другой форме, перестал бы находиться. Записываем мы всегда NFC, значит в
 * указателе и на диске лежит одно и то же; менять это по дороге незачем.
 */
export function shardFileName(file: string): string | undefined {
  const prefix = `${EXPORT_BOOKS_FOLDER_NAME}/`;
  if (!file.startsWith(prefix)) return undefined;
  const name = file.slice(prefix.length);
  if (name === "" || name === "." || name === "..") return undefined;
  if (name.includes("/")) return undefined;
  return name;
}
