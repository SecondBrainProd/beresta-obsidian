import { fileURLToPath } from "node:url";

import { defineConfig } from "vitest/config";

// **Почему у `obsidian` подстановка.** Пакет `obsidian` из npm — одни
// описания типов: исполняемого кода в нём нет вовсе, само приложение отдаёт
// свой во время работы. Значит любой тест, который импортирует наш код,
// спотыкается на первой строке `main.ts` — не о нашей ошибке, а о том, что
// разрешать нечего.
//
// Границу проводим так: **типы берутся из настоящего пакета** (`tsc` видит
// `node_modules/obsidian/obsidian.d.ts` и ловит расхождение с API), а под
// прогон подставляется двойник ровно той толщины, какая нужна, чтобы импорт
// разрешился. Двойник не изображает поведение Obsidian и не должен: то, что
// требует настоящего Obsidian, проверяется швом на живом приложении
// (задача 13), а не подделкой, которая всегда согласна.
export default defineConfig({
  test: {
    include: ["test/**/*.test.ts"],
  },
  resolve: {
    alias: {
      obsidian: fileURLToPath(new URL("test/obsidian-stub.ts", import.meta.url)),
    },
  },
});
