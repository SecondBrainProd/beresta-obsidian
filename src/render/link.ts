/**
 * Обратная ссылка из заметки в приложение: `beresta://open/<uuid>?cfi=<место>`.
 *
 * **Это вторая общая граница со Swift, и она молчаливее первой.** Схему, узел
 * и имя поля объявляет `DeepLink` в `packages/beresta-core`; здесь они собраны
 * второй раз, потому что плагин — отдельная программа и импортировать Swift
 * ему нечем. Разойдись стороны — ссылка в заметке останется красивой и живой
 * на вид, а нажатие не откроет ничего: ни ошибки, ни следа. Поэтому равенство
 * сверяется тестом, который читает объявления прямо из `DeepLink.swift`.
 *
 * **Узел `open`, а не `book`.** Схема `beresta://` занята изнутри: веб-окно
 * читалки берёт по ней байты книги (`beresta://book/<sha256>`), свой код и
 * шрифты. Узел — единственный признак, отличающий ссылку из заметки от
 * внутреннего запроса читалки; разводить длиной идентификатора отказались в
 * задаче 7 нарочно.
 */

/** Наша схема — общая с внутренними адресами читалки. */
export const LINK_SCHEME = "beresta";

/** Публичный узел. Единственный признак ссылки из заметки. */
export const LINK_HOST = "open";

/** Имя поля с местом в тексте. */
export const LINK_CFI_QUERY = "cfi";

/**
 * Собирает ссылку на книгу и место в ней. Пустой `uuid` — ссылки нет вовсе.
 *
 * Пустая строка вместо ссылки — не забывчивость, а единственный честный ответ
 * для осколка сирот: у выписки, потерявшей книгу, открывать нечего, и адрес
 * `beresta://open/?cfi=…` вёл бы человека в ошибку вместо книги. Что рисовать
 * на месте отсутствующей ссылки, решает отрисовка, а не сборщик адреса.
 */
export function bookOpenLink(uuid: string, cfi?: string): string {
  if (uuid === "") return "";
  const base = `${LINK_SCHEME}://${LINK_HOST}/${encodeStrict(uuid)}`;
  if (cfi === undefined || cfi === "") return base;
  return `${base}?${LINK_CFI_QUERY}=${encodeStrict(cfi)}`;
}

/**
 * Кодирует всё, кроме незарезервированных знаков RFC 3986 (`A–Z a–z 0–9 -._~`).
 *
 * **Строгость здесь куплена дорогой ошибкой.** Стандарт разрешает в запросе и
 * скобки, и двоеточия, и косые — то есть почти весь набор знаков CFI. Но
 * ссылку читает не только разбор приложения: она проходит через разметку
 * заметки (где `)` закрывает `[…](…)` — и ссылка обрывается ровно на первой
 * скобке `epubcfi(`), через чужую синхронизацию хранилища и через механизм
 * открытия схем в системе. Оборванная ссылка приводит человека НЕ ТУДА, а не
 * «никуда»: место теряется молча.
 *
 * **Расхождение со Swift названо, а не спрятано.** Там список разрешённого —
 * `CharacterSet.alphanumerics` плюс `-._~`, а `alphanumerics` в Foundation
 * включает и буквы за пределами латиницы. То есть кириллица в CFI у Swift
 * уехала бы в адрес как есть, а у нас уедет закодированной. Оба адреса
 * разбираются `DeepLink.parse` в одно и то же (он раскодирует), оба верны по
 * RFC 3986; мы выбрали более строгий, потому что путь ссылки лежит через
 * Markdown, а не потому, что Swift неправ.
 */
function encodeStrict(value: string): string {
  let out = "";
  for (const character of value) {
    if (/^[A-Za-z0-9\-._~]$/.test(character)) {
      out += character;
      continue;
    }
    const encoded = encodeURIComponent(character);
    // `encodeURIComponent` оставляет нетронутыми `!'()*` — по RFC 3986 это
    // подразделители, а не незарезервированные знаки. Скобка среди них, и
    // именно скобка обрывает ссылку в разметке заметки, так что дописываем
    // руками. Все пятеро — знаки ASCII, значит один байт и два знака hex.
    out +=
      encoded === character
        ? `%${character.charCodeAt(0).toString(16).toUpperCase().padStart(2, "0")}`
        : encoded;
  }
  return out;
}
