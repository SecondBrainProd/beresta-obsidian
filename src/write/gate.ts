/**
 * Пускать ли запись в эту заметку прямо сейчас.
 *
 * **Замер задачи 2, вопрос 3 — измерено, не предположено.** Заметка открыта в
 * редакторе, человек набрал строку и НЕ сохранил. В этот момент:
 *
 * 1. обработчику `vault.process()` достаётся текст **с диска** — несохранённой
 *    строки человека в нём нет;
 * 2. на диск уходит результат обработчика, то есть версия без его строки;
 * 3. редактор затем сводит своё несохранённое с новым содержимым файла и
 *    пишет свод обратно.
 *
 * Текст человека при этом не теряется — и ровно поэтому беда незаметна.
 * Измеренный итог: машина записала `## Открытый файл` + коллаут + якорь, а на
 * диске оказалось
 *
 * ```
 * ## Открытый файл
 *
 * РУЧНАЯ ПРАВКА В РАБОТЕ
 * > [!quote]+ Выгрузка Beresta
 * > цитата из книги
 *
 * ^hl-aaaa1111
 * ```
 *
 * — строка человека влезла **внутрь машинного блока**. Ничего не пропало, но
 * блок стал грязным, а его хеш — чужим. И вот что это значит дальше: задача 11
 * различает «наш блок» и «правка человека» сравнением хешей. Следующий проход
 * увидит несовпадение, решит, что человек правил блок, и **заморозит его
 * навсегда**. Одна несохранённая строка — и выписка в этой заметке перестаёт
 * обновляться, молча и насовсем.
 *
 * **Решение: при несохранённых правках запись откладывается и говорится
 * вслух.** Не «пишем, потом починим» — чинить будет нечего, смесь неотличима
 * от правки человека по устройству. Не «пишем молча» — это и есть та самая
 * молчаливая запись поверх, после которой человек не понимает, откуда в его
 * конспекте машинный блок с его строкой внутри. Откладывание ничего не стоит:
 * снимок никуда не денется, а следующий проход застанет буфер чистым.
 *
 * **Почему признак — сравнение с диском, а не «флаг грязного буфера».** В
 * `obsidian.d.ts` такого флага нет: `MarkdownView` объявляет `editor` и
 * `file`, но не состояние сохранённости. Строить работу на непубличном поле
 * значило бы получить плагин, который сломается тихо при обновлении Obsidian.
 * Сравнение же меряет ровно то расхождение, которое и порождает беду: что
 * видит человек против того, что увидит запись.
 */

/** Пускать ли запись — и если нет, что сказать человеку. */
export type WriteVerdict =
  | { kind: "may-write" }
  | {
      kind: "defer";
      reason: "dirty-buffer";
      path: string;
      message: string;
    };

/** Что известно про заметку в момент решения. */
export interface WriteConditions {
  /** Путь заметки в хранилище — только чтобы назвать её человеку. */
  readonly path: string;
  /** Содержимое файла на диске: ровно то, что увидит `vault.process`. */
  readonly onDisk: string;
  /**
   * Содержимое буфера редактора, если заметка открыта хоть в одной вкладке.
   * `undefined` — заметка не открыта, буфера нет вовсе.
   */
  readonly inEditor: string | undefined;
}

/**
 * Решает, можно ли писать.
 *
 * Чистая функция: ни `vault`, ни `workspace`, ни времени, ни настроек. Всё,
 * что нужно, приходит входом, — и значит проверяется обычным тестом, а не
 * живым Obsidian, где эту ветку пришлось бы ловить руками с секундомером.
 *
 * **Звать её обязан тот, кто пишет, и звать дважды.** Один раз до записи —
 * чтобы не готовить текст впустую. Второй раз ВНУТРИ обработчика
 * `vault.process`, где текст с диска уже на руках: обработчик выполняется
 * синхронно, JS однопоточен, и в этот промежуток человек напечатать ничего не
 * успевает. Отложились внутри обработчика — возвращаем полученный текст без
 * изменений, ни байта своего.
 */
export function writeVerdict(conditions: WriteConditions): WriteVerdict {
  const { path, onDisk, inEditor } = conditions;
  if (inEditor === undefined) return { kind: "may-write" };
  if (inEditor === onDisk) return { kind: "may-write" };
  return {
    kind: "defer",
    reason: "dirty-buffer",
    path,
    message:
      `Заметка «${path}» открыта, и в ней есть несохранённые правки. Beresta не ` +
      "пишет в неё сейчас: запись видит файл на диске, а не то, что у вас на " +
      "экране, — ваша строка попала бы внутрь машинного блока, и он замёрз бы " +
      "навсегда. Сохраните заметку, и выписки приедут следующим проходом.",
  };
}
